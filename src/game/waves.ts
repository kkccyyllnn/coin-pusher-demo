/**
 * 波次目标表（1c）：一局之内"递增目标"的唯一真源。
 *
 * ## 为什么要有波
 *
 * 破产仍然是核心产出（负 EV 保留），但被降为**软约束**（10-07 用户拍板）：
 * 光有"迟早会破产"没有正反馈，一局就变成了纯等待。波次给的是**局内的短目标**——
 * 攒够票券 ⇒ 三选一 ⇒ 构筑变强，然后把下一波的目标抬高一点。
 * 长期斜率仍由事件扣款（胡萝卜四连的比例罚金、催债币）拉回负。
 *
 * ## 这张表**暂时只是形状**，不是标定值
 *
 * 计划里写得很明白：形状先线性 `+1` 档/波，标定轮再拟合。
 * 定档的依据是 `economy` 新加的「波次到达率分布」（n≥20，报分布不报点值）——
 * 在那批读数出来之前，下面两个数**不许被引用成"平衡过的"**。
 *
 * 口径：`waveTarget(n)` 是**第 n 波内部**要挣到的票券数（不是累计），
 * 因为票券会被三选一花掉，累计口径会让"花钱"变成惩罚。
 */

/** 第 1 波的目标（枚）。取 1 ⇒ 第一波几乎必到，先让玩家看见"三选一"这个仪式。 */
export const WAVE_TARGET_BASE = 1;

/** 每往下一波加多少枚（线性）。 */
export const WAVE_TARGET_STEP = 1;

/** 三选一选一张要花多少票券（唯一"减"的出口 —— 票券恒等式的汇就靠它，见 1b）。 */
export const DRAFT_COST = 1;

/** 一次最多摆几张候选（面板的槽位数，`#draft-panel` 的按钮数与它同源）。 */
export const DRAFT_CHOICES = 3;

/**
 * 第 `wave` 波（1 起）的目标票券数。
 *
 * 非正档位一律回落到第 1 波的目标 —— 波次号是从存档/快照读进来的外部值，
 * 读到 0 或负数不该让目标变成负数（那会让波**瞬间完成**，是条静默的假绿）。
 */
export function waveTarget(wave: number): number {
  const n = Math.max(1, Math.floor(wave));
  return WAVE_TARGET_BASE + WAVE_TARGET_STEP * (n - 1);
}

/** 走到第 `wave` 波（含本波）至少需要挣到的总票数 —— 给判据和 HUD 进度条用。 */
export function ticketsNeededForWave(wave: number): number {
  const n = Math.max(1, Math.floor(wave));
  let sum = 0;
  for (let i = 1; i <= n; i += 1) sum += waveTarget(i);
  return sum;
}

/* ── 票券的**源**（1b）──────────────────────────────────────────────────────── */

/**
 * 每多少**枚越线**发一张票券。
 *
 * 取 12 的推导（形状级别的估算，标定轮要换成实测）：S6 终稿实测越线 ≈ 0.92 枚/投，
 * 所以这一档给 `0.92/12 ≈ 0.077` 券/投 ⇒ 中位局长 90 投约 7 张，
 * 对着上面那张 `1,2,3,…` 的目标表正好走到第 3~4 波（`1+2+3 = 6`）。
 * **这条是票券唯一的大源**，另外两条都是点缀 —— 判据按源分别对账，不是只对总数。
 *
 * ⚠️ 票券**不是筹码**：它不进 `balance` 恒等式（`economy.ts` 那条一字不改），
 * 也不参与跪求闸（`spendableOf`）—— 脏钱刷不出构筑，这正是分两种货币的理由。
 */
export const TICKET_EVERY_CROSSINGS = 12;

/**
 * 发券间隔的下限（「票孔」候选能把 12 减到多小）。
 *
 * 有下限是因为票券是**波次目标的分子**：间隔减到 1 就是"每枚越线一张券"，
 * 于是波与波之间几乎没有内容，一屏三选一直接推到局长尽头 ——
 * 那等于把这张表作废。4 是"最快也还在 4 枚一张"的整数位，标定轮要复看。
 */
export const TICKET_INTERVAL_FLOOR = 4;

/** 连落达到这一档时补发一张（每**串**只发一次，不是每枚都发）。 */
export const TICKET_COMBO_TIER = 5;

/** 老虎机四同（大奖）一次给几张。四同本身约 0.0014 次/投 ⇒ 贡献 ≈ 0.003 券/投，点缀级。 */
export const TICKET_JACKPOT = 2;

/** 票券的来源名（判据逐个对账用；新增源要同时进 `RunState` 的计数与 economy 的门）。 */
export type TicketSource = 'crossing' | 'combo' | 'jackpot' | 'effect';

